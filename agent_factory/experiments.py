def canonical_hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                     separators=(",", ":")).encode()).hexdigest()


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def ollama_model_identity(base_url, model, transport=None):
    """Resolve the exact installed model digest without invoking generation."""
    with httpx.Client(timeout=20, trust_env=False, transport=transport) as client:
        response = client.get(base_url.rstrip("/") + "/api/tags")
        response.raise_for_status()
        matches = [item for item in response.json()["models"]
                   if item.get("name") == model or item.get("model") == model]
    if len(matches) != 1 or not re.fullmatch(r"(?:sha256:)?[a-fA-F0-9]{64}", matches[0].get("digest", "")):
        raise ValueError("Expected one exact installed model with an immutable digest: " + model)
    return {"name": model, "digest": matches[0]["digest"]}


def _package_hashes():
    package = Path(__file__).parent
    return {str(path.relative_to(package)): file_hash(path) for path in sorted(package.rglob("*"))
            if path.is_file() and path.suffix in {".py", ".json", ".md"}}


def _input_hashes(source):
    inputs = {str(path.relative_to(source)): file_hash(path)
              for directory in ["data", "config", "knowledge/sources"]
              for path in sorted((source / directory).rglob("*")) if path.is_file()}
    inputs["config.json"] = file_hash(source / "config.json")
    return inputs


def _write(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    temporary.replace(path)


def _graph_rows(store):
    with store.connect() as db:
        nodes = [{"id": uid, "kind": kind, "payload": json.loads(payload)}
                 for uid, kind, payload in db.execute("SELECT id,kind,payload FROM nodes ORDER BY id")]
        edges = [list(row) for row in db.execute("SELECT source,target,relation FROM edges ORDER BY source,target,relation")]
    return {"nodes": nodes, "edges": edges}


def _repair_trace_evidence(workspace, run, implementation, parent, code_path, parent_path):
    """Corroborate a changed implementation with its successful model response.

    These local records are auditable provenance, not a cryptographic attestation
    by the provider. Legacy traces have no transport marker and remain explicitly
    labelled; an explicitly overridden/test transport cannot supply real history.
    """
    generation = implementation.get("generation", {})
    if generation.get("backend") != "llm" or generation.get("llm_code_generated") is not True:
        raise ValueError("Verified repair was not generated by the LLM backend")
    if file_hash(parent_path) != parent["code_hash"]:
        raise ValueError("Failed parent code is missing or its hash changed")
    code = code_path.read_text(encoding="utf-8")
    previous = parent_path.read_text(encoding="utf-8")
    if code_fingerprint(code) == code_fingerprint(previous):
        raise ValueError("Verified repair did not change the parent implementation semantics")
    matches = []
    trace_directory = workspace / "runs" / run["run_id"] / "llm"
    for path in sorted(trace_directory.glob("*.json")):
        trace = json.loads(path.read_text(encoding="utf-8"))
        context = trace.get("context", {})
        response = trace.get("response", {})
        response_code = response.get("code") if isinstance(response, dict) else None
        if (trace.get("role") != "repairer" or trace.get("provider") != run.get("provider")
                or trace.get("provider") not in REAL_PROVIDERS
                or trace.get("generation_backend") != "llm" or trace.get("model") != run["model"]
                or trace.get("error") or not isinstance(response_code, str)
                or hashlib.sha256(response_code.encode()).hexdigest() != implementation["code_hash"]):
            continue
        if trace.get("transport_kind") not in {None, "http"}:
            raise ValueError("Custom/test transport cannot supply real repair history")
        if (context.get("candidate", {}).get("algorithm") != implementation["algorithm"]
                or context.get("request", {}).get("task") != run["request"]["task"]
                or context.get("repair_strategy") != generation.get("strategy")):
            continue
        parent_code = context.get("previous_code")
        parent_hash = (hashlib.sha256(parent_code.encode()).hexdigest()
                       if isinstance(parent_code, str) else context.get("failed_code_hash"))
        if parent_hash != parent["code_hash"]:
            continue
        # Legacy traces used a JSON artifact. New source-only responses must be
        # decoded by the same strict, non-rewriting protocol as the LLM client;
        # neither a matching AST nor an edited response field is provenance.
        cloud_identity = {}
        if trace.get("provider") == "deepseek":
            # An API model name is an observation, never a pinned model digest.
            # Unlike legacy Ollama records, new cloud evidence must archive the
            # actual messages and corroborate the failed parent in those messages.
            wire = trace.get("messages")
            if (trace.get("transport_kind") != "http" or not isinstance(wire, list)
                    or not trace.get("response_model")):
                raise ValueError("DeepSeek history requires HTTP wire messages and a returned model name")
            wire_contexts = []
            for message in wire:
                if not isinstance(message, dict) or message.get("role") != "user":
                    continue
                try:
                    value = json.loads(message.get("content"))
                except (TypeError, ValueError):
                    continue
                if isinstance(value, dict):
                    wire_contexts.append(value)
            same_request = any(value.get("candidate", {}).get("algorithm") == implementation["algorithm"]
                               and value.get("request", {}).get("task") == run["request"]["task"]
                               for value in wire_contexts)
            same_parent = any(isinstance(message, dict) and message.get("role") == "assistant"
                              and message.get("content") == previous for message in wire)
            same_parent = same_parent or any(value.get("failed_code_hash") == parent["code_hash"]
                                            or value.get("previous_code") == previous for value in wire_contexts)
            if not same_request or not same_parent:
                raise ValueError("DeepSeek repair wire messages do not corroborate the request and failed parent")
            cloud_identity = {"model_identity_verification": "unverifiable_remote_service",
                              "requested_model": trace["model"],
                              "returned_model": trace["response_model"],
                              "response_id": trace.get("response_id"),
                              "system_fingerprint": trace.get("system_fingerprint"),
                              "wire_messages_sha256": canonical_hash(wire)}
        response_protocol = trace.get("response_protocol", JSON_ARTIFACT_PROTOCOL)
        try:
            raw_response = decode_code_response(trace["raw_content"], response_protocol)
        except (KeyError, TypeError, ValueError):
            continue
        if raw_response != response:
            continue
        matches.append({"repair_trace_path": str(path), "repair_trace_sha256": file_hash(path),
                        "transport_kind": trace.get("transport_kind", "legacy_unspecified"),
                        "response_protocol": response_protocol,
                        "prior_code_path": str(parent_path), "prior_code_hash": parent["code_hash"],
                        "semantic_hash": code_fingerprint(code),
                        "prior_semantic_hash": code_fingerprint(previous), **cloud_identity})
    if len(matches) != 1:
        provider_name = "Ollama" if run.get("provider") == "ollama" else "DeepSeek"
        raise ValueError("Verified repair requires one matching successful " + provider_name + " repairer response")
    return matches[0]


def freeze_history(workspaces, output):
    """Freeze verified repair chains from independent real runs, rejecting mock history.

No final-test outcomes are copied. A graph claim is insufficient: the archived
FactoryRun, both validation outcomes, edge relations, and fixed source hash must
corroborate the claimed repair. Original files remain the external audit evidence.
    """
    output = Path(output).resolve()
    if output.exists():
        raise ValueError("Snapshot output already exists; choose a new immutable path")
    retained, edges, evidence = {}, set(), []

    def keep(uid, data):
        row = {"id": uid, "kind": data["kind"], "payload": data["payload"]}
        if uid in retained and retained[uid] != row:
            raise ValueError("Conflicting immutable knowledge node: " + uid)
        retained[uid] = row

    for workspace in workspaces:
        workspace = Path(workspace).resolve()
        database = workspace / "state/knowledge.sqlite"
        if not database.is_file():
            raise ValueError("Missing history database: " + str(database))
        store = KnowledgeStore(database)
        graph = store.graph()
        runs = store.nodes("FactoryRun")
        for uid, data in graph.nodes(data=True):
            if data["kind"] in {"Source", "Capability"}:
                keep(uid, data)
        for uid, data in graph.nodes(data=True):
            lesson = data["payload"]
            if (data["kind"] != "Lesson" or not lesson.get("validated_fix")
                    or not lesson.get("evidence", {}).get("prior_validation_id")):
                continue
            impl_id = lesson.get("implementation_id")
            val_id = lesson.get("evidence", {}).get("validation_id")
            if impl_id not in graph or val_id not in graph:
                raise ValueError("Verified lesson has no implementation/validation evidence")
            implementation = graph.nodes[impl_id]["payload"]
            validation = graph.nodes[val_id]["payload"]
            matching_runs = [run for run in runs if any(
                attempt["implementation_id"] == impl_id for attempt in run.get("attempts", []))]
            if len(matching_runs) != 1:
                raise ValueError("Verified lesson must have one auditable source run")
            run = matching_runs[0]
            if run.get("provider") not in REAL_PROVIDERS or run.get("mock_fault_injection"):
                continue
            algorithm = implementation["algorithm"]
            attempts = [item for item in run["attempts"] if item["algorithm"] == algorithm]
            failed = next((item for item in attempts if item["revision"] == 0
                           and not item["validation"]["passed"]), None)
            repaired = next((item for item in attempts if item["implementation_id"] == impl_id), None)
            if not failed or not repaired or implementation["revision"] < 1:
                continue
            if not validation.get("passed") or validation.get("split") != "validation":
                raise ValueError("Claimed repair did not pass trusted validation")
            if repaired["validation"] != validation or repaired["code_hash"] != implementation["code_hash"]:
                raise ValueError("Run and graph repair evidence disagree")
            if repaired.get("generation") != implementation.get("generation"):
                raise ValueError("Run and graph repair generation evidence disagree")
            if lesson.get("algorithm") != algorithm or lesson.get("scope") != run["request"]["task"]:
                raise ValueError("Lesson algorithm/task differs from the verified run")
            code_path = Path(implementation["code_path"])
            if not code_path.is_absolute():
                code_path = workspace / code_path
            if not code_path.is_file() or file_hash(code_path) != implementation["code_hash"]:
                raise ValueError("Verified repaired code is missing or its hash changed")
            if lesson.get("evidence", {}).get("code_hash") != implementation["code_hash"]:
                raise ValueError("Lesson source hash differs from repaired implementation")
            failed_impl = failed["implementation_id"]
            failed_vals = [target for _, target, attrs in graph.out_edges(failed_impl, data=True)
                           if attrs["relation"] == "validated_by"] if failed_impl in graph else []
            if len(failed_vals) != 1 or graph.nodes[failed_vals[0]]["payload"] != failed["validation"]:
                raise ValueError("Missing trusted first-failure evidence")
            cap_id = implementation["capability_id"]
            required_edges = [(cap_id, impl_id, "realized_by"), (impl_id, val_id, "validated_by"),
                              (val_id, uid, "produced")]
            for source, target, relation in required_edges:
                if not graph.has_edge(source, target) or graph.edges[source, target]["relation"] != relation:
                    raise ValueError("Broken verified repair provenance edge")
            prior_val = lesson["evidence"]["prior_validation_id"]
            prior_impl = implementation.get("parent")
            if prior_val not in graph or prior_impl not in graph:
                raise ValueError("Verified lesson is missing its immediate failed parent")
            if lesson.get("parent") != prior_impl:
                raise ValueError("Lesson and implementation disagree on the failed parent")
            if (graph.nodes[prior_val]["payload"].get("passed")
                    or graph.nodes[prior_val]["payload"].get("split") != "validation"):
                raise ValueError("Lesson parent did not fail validation")
            if graph.nodes[prior_impl]["payload"]["code_hash"] != lesson["evidence"].get("prior_code_hash"):
                raise ValueError("Lesson parent implementation hash is inconsistent")
            parent = graph.nodes[prior_impl]["payload"]
            parent_path = Path(parent["code_path"])
            if not parent_path.is_absolute():
                parent_path = workspace / parent_path
            if not parent_path.is_file():
                raise ValueError("Failed parent code is missing or its hash changed")
            for source, target, relation in [(prior_impl, prior_val, "validated_by"), (impl_id, prior_impl, "revises")]:
                if not graph.has_edge(source, target) or graph.edges[source, target]["relation"] != relation:
                    raise ValueError("Broken failed-parent repair provenance edge")
            trace_evidence = _repair_trace_evidence(workspace, run, implementation, parent, code_path, parent_path)
            # Re-extract from the verified immutable pair. Older Lesson writers
            # may have omitted a useful fix; never edit their archived records.
            previous_validation = graph.nodes[prior_val]["payload"]
            requirements = run.get("validation_config", previous_validation.get("gates", {})).get("requirements", [])
            rules = observed_repair_rules(parent_path.read_text(encoding="utf-8"),
                                          code_path.read_text(encoding="utf-8"), previous_validation, requirements)
            if not rules:
                continue
            extraction_audit = {"version": REPAIR_RULE_EXTRACTOR_VERSION,
                                "source_lesson_sha256": canonical_hash(lesson),
                                "original_repair_rules": lesson.get("repair_rules", []),
                                "basis": "verified parent/repaired source and prior validation; no reviewer advice"}
            frozen_lesson = {**lesson, "repair_rules": rules, "rule_extraction": extraction_audit}
            selected = {uid, impl_id, val_id, cap_id, failed_impl, failed_vals[0], prior_val, prior_impl}
            for node in selected:
                keep(node, {"kind": "Lesson", "payload": frozen_lesson} if node == uid else graph.nodes[node])
            evidence.append({"lesson_id": uid, "workspace": str(workspace), "run_id": run["run_id"],
                             "task": lesson["scope"], "algorithm": algorithm,
                             "provider": run["provider"], "model": run["model"],
                             "generation_mode": run.get("validation_config", {}).get("generation_mode", "reference"),
                             "first_attempt_strategy": failed.get("generation", {}).get("strategy"),
                             "repair_strategy": repaired.get("generation", {}).get("strategy"),
                             "failed_revision": 0, "repaired_revision": implementation["revision"],
                             "code_hash": implementation["code_hash"], "code_path": str(code_path),
                             "rule_extraction": extraction_audit, "repair_rules": rules,
                             **trace_evidence})
        for source, target, attrs in graph.edges(data=True):
            if source in retained and target in retained:
                edges.add((source, target, attrs["relation"]))
    if not evidence:
        raise ValueError("No real, verified failed-to-passed repair exists; run independent warmups first")
    output.mkdir(parents=True)
    frozen = KnowledgeStore(output / "knowledge.sqlite")
    for row in retained.values():
        frozen.add_node(row["id"], row["kind"], row["payload"])
    for edge in sorted(edges):
        frozen.add_edge(*edge)
    snapshot = {"schema_version": 2, "created_at": datetime.now(timezone.utc).isoformat(),
                "rule_extraction_version": REPAIR_RULE_EXTRACTOR_VERSION,
                "graph_sha256": canonical_hash(_graph_rows(frozen)),
                "evidence": sorted(evidence, key=lambda item: item["lesson_id"]),
                "excludes": ["final-test outcomes", "mock histories", "unverified diagnoses", "FactoryRun reports"]}
    _write(output / "snapshot.json", snapshot)
    return snapshot


def validate_snapshot(directory, profiles):
    directory = Path(directory)
    manifest = json.loads((directory / "snapshot.json").read_text(encoding="utf-8"))
    if manifest.get("rule_extraction_version") != REPAIR_RULE_EXTRACTOR_VERSION:
        raise ValueError("Frozen history rule extractor version differs; create a fresh snapshot")
    store = KnowledgeStore(directory / "knowledge.sqlite")
    if canonical_hash(_graph_rows(store)) != manifest["graph_sha256"]:
        raise ValueError("Frozen history snapshot changed")
    for evidence in manifest["evidence"]:
        path = Path(evidence["code_path"])
        if not path.is_file() or file_hash(path) != evidence["code_hash"]:
            raise ValueError("Frozen history external repaired-code evidence is missing or changed")
        for path_key, hash_key in [("prior_code_path", "prior_code_hash"),
                                   ("repair_trace_path", "repair_trace_sha256")]:
            path = Path(evidence[path_key])
            if not path.is_file() or file_hash(path) != evidence[hash_key]:
                raise ValueError("Frozen history external parent/trace evidence is missing or changed")
    lessons = store.nodes("Lesson")
    for profile in profiles:
        matched = [lesson for lesson in lessons if lesson.get("validated_fix")
                   and lesson.get("scope") == profile["task"] and lesson.get("algorithm") == profile["algorithm"]]
        if not matched:
            raise ValueError("No verified history for profile: " + profile["id"])
        if not any(item["task"] == profile["task"] and item["algorithm"] == profile["algorithm"]
                   and item["provider"] in REAL_PROVIDERS for item in manifest["evidence"]):
            raise ValueError("No real source provenance for profile: " + profile["id"])
        retrieved = store.retrieve(profile["description"], algorithms=[profile["algorithm"]])
        if not compact_lessons(retrieved, profile["algorithm"], profile["task"]):
            raise ValueError("Selected capability cannot retrieve verified prose-only history: " + profile["id"])
    return manifest


def _profile_config(source, profile, seed, history, max_repairs):
    config = load_task_config(source, profile["task"]).model_dump()
    config.update(algorithms=[profile["algorithm"]], max_candidates=1, compare_all_algorithms=True,
                  generation_mode="spec", history_mode=history, model_seed=seed,
                  requirements=profile["requirements"], max_repairs=max_repairs)
