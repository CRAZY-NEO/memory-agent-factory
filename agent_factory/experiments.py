def _copy_inputs(source, destination, snapshot=None):
    destination.mkdir(parents=True, exist_ok=False)
    for name in ["data", "config", "knowledge/sources"]:
        if (source / name).exists():
            shutil.copytree(source / name, destination / name)
    shutil.copyfile(source / "config.json", destination / "config.json")
    if snapshot is not None:
        (destination / "state").mkdir()
        shutil.copyfile(snapshot / "knowledge.sqlite", destination / "state/knowledge.sqlite")


def _nested_keys(value):
    if isinstance(value, dict):
        for key, item in value.items():
            yield key
            yield from _nested_keys(item)
    elif isinstance(value, list):
        for item in value:
            yield from _nested_keys(item)


def _history_values(value):
    if isinstance(value, dict):
        for key, item in value.items():
            if key in HISTORY_KEYS:
                yield item
            yield from _history_values(item)
    elif isinstance(value, list):
        for item in value:
            yield from _history_values(item)


def collect_unit(factory, profile, seed, history, elapsed, error=None, expected_lessons=()):
    """Retain every provider attempt, including failed JSON and transport retries."""
    directory = factory.directory
    report_path = directory / "report.json"
    report = json.loads(report_path.read_text()) if report_path.exists() else {}
    attempts = report.get("attempts", [])
    if not report:
        # A late workflow error must not erase earlier candidate outcomes.
        for path in sorted((directory / profile["algorithm"]).glob("r*/validation.json")):
            code_files = [item for item in path.parent.glob("*.py") if item.is_file()]
            attempts.append({"revision": int(path.parent.name[1:]),
                             "code_hash": file_hash(code_files[0]) if len(code_files) == 1 else None,
                             "validation": json.loads(path.read_text(encoding="utf-8"))})
    traces, delivered_ids, violations = [], set(), []
    for path in sorted((directory / "llm").glob("*.json")):
        trace = json.loads(path.read_text(encoding="utf-8"))
        context = trace.get("context", {})
        # New traces archive the actual request messages. Only user JSON carries
        # structured context; assistant source and plain retry instructions remain
        # opaque, even when their text happens to resemble JSON.
        wire_contexts = []
        has_wire_messages = "messages" in trace
        if has_wire_messages:
            messages = trace["messages"]
            if not isinstance(messages, list):
                violations.append("Invalid wire messages in provider trace: " + path.name)
            else:
                for message in messages:
                    if not isinstance(message, dict):
                        violations.append("Invalid wire message in provider trace: " + path.name)
                        continue
                    if message.get("role") != "user":
                        continue
                    try:
                        value = json.loads(message.get("content"))
                    except (TypeError, ValueError):
                        continue  # Format-retry requests may be ordinary prose.
                    if isinstance(value, (dict, list)):
                        wire_contexts.append(value)
        delivery_context = wire_contexts if has_wire_messages else [context]
        encoded_delivery = json.dumps(delivery_context, ensure_ascii=False)
        found = {uid for uid in expected_lessons if uid in encoded_delivery}
        if trace["role"] in {"coder", "repairer"}:
            delivered_ids.update(found)
            if history == "on" and not found:
                origin = "wire messages" if has_wire_messages else "context"
                violations.append(f"Frozen lesson missing from on generation {origin}: " + path.name)
            if (trace.get("provider", "ollama") == "ollama"
                    and trace.get("options") and trace["options"].get("seed") != seed):
                violations.append("Generation sampling seed differs from paired protocol: " + path.name)
        audit_contexts = [context, *wire_contexts]
        keys = set(_nested_keys(audit_contexts))
        if REFERENCE_KEYS.intersection(keys):
            violations.append("Reference implementation field in spec experiment: " + path.name)
        if history == "off" and any(_history_values(audit_contexts)):
            violations.append("Nonempty history in off context: " + path.name)
        prompt = {key: trace[key] for key in ["system", "system_prompt", "context", "schema", "options"] if key in trace}
        traces.append({"path": str(path), "sha256": file_hash(path), "prompt_sha256": canonical_hash(prompt),
                       "wire_messages_sha256": canonical_hash(trace["messages"]) if has_wire_messages else None,
                       "role": trace["role"], "retry": trace.get("retry", 0),
                       "provider": trace.get("provider"), "requested_model": trace.get("model"),
                       "returned_model": trace.get("response_model"),
                       "response_id": trace.get("response_id"),
                       "system_fingerprint": trace.get("system_fingerprint"),
                       "requested_model_seed": trace.get("requested_model_seed", trace.get("model_seed")),
                       "seed_supported": trace.get("seed_supported", trace.get("provider", "ollama") == "ollama"),
                       "provider_usage": trace.get("provider_usage", {}),
                       "usage": trace.get("usage", {}), "duration_seconds": trace.get("duration_seconds"),
                       "error": trace.get("error"), "error_type": trace.get("error_type"),
                       "http_status": trace.get("http_status"),
                       "options": trace.get("options", {}),
                       "lesson_ids": sorted(found)})
    code_roles = any(trace["role"] in {"coder", "repairer"} for trace in traces)
    if history == "on" and code_roles and not delivered_ids:
        violations.append("No frozen verified lesson reached a coder/repairer")
    first = [attempt for attempt in attempts if attempt["revision"] == 0]
    return {"profile": profile["id"], "task": profile["task"], "algorithm": profile["algorithm"],
            "seed": seed, "history_mode": history, "run_id": factory.run_id, "directory": str(directory),
            "seed_application": ("unsupported_by_provider" if any(row["provider"] == "deepseek" for row in traces)
                                 else "recorded_in_trace_options"),
            "status": report.get("status", "error"), "error": error,
            "first_pass": bool(first and all(row["validation"]["passed"] for row in first)),
            "validation_pass": any(row["validation"]["passed"] for row in attempts),
            "final_pass": report.get("status") == "passed", "prompt_audit_violations": violations,
            "repairs": sum(row["revision"] > 0 for row in attempts), "calls": len(traces),
            "provider_attempt_errors": sum(bool(trace["error"]) for trace in traces),
            "transport_attempt_errors": sum(bool(trace["http_status"] and trace["http_status"] >= 400)
                                            or trace["error_type"] in {"ConnectError", "ConnectTimeout", "ReadTimeout",
                                                                        "ReadError", "RemoteProtocolError", "WriteError",
                                                                        "WriteTimeout", "PoolTimeout", "HTTPStatusError"}
                                            for trace in traces),
            "observed_prompt_tokens": sum(trace["usage"].get("prompt_eval_count") or 0 for trace in traces),
            "observed_output_tokens": sum(trace["usage"].get("eval_count") or 0 for trace in traces),
            "usage_missing_attempts": sum(any(trace["usage"].get(key) is None
                                               for key in ("prompt_eval_count", "eval_count")) for trace in traces),
            "wall_seconds": elapsed, "delivered_lesson_ids": sorted(delivered_ids),
            "actual_generation_options": [trace["options"] for trace in traces
                                          if trace["role"] in {"coder", "repairer"}],
            "metrics": (report.get("test") or {}).get("metrics", {}),
            "attempts": [{"revision": row["revision"], "code_hash": row["code_hash"],
                          "passed": row["validation"]["passed"], "errors": row["validation"]["errors"]}
                         for row in attempts], "traces": traces}


def aggregate_results(results, planned_pairs, provider, protocol_kind=None):
    """Intent-to-run denominator: errors and missing units are not silently dropped."""
    if type(planned_pairs) is not int or planned_pairs < 1:
        raise ValueError("planned_pairs must be a positive integer")
    summary = {"planned_pairs": planned_pairs, "planned_runs": 2 * planned_pairs,
               "completed_units": len(results), "provider": provider,
               "evidence_kind": ("real_model_observation" if provider in REAL_PROVIDERS
                                 else "mock_mechanism_only" if provider == "mock" else "unsupported_provider"),
               "denominator_policy": "All planned units per arm, including workflow/provider failures and missing units",
               "first_pass_definition": "Candidate revision r0 passes trusted validation, after any bounded response-format retry",
               "final_pass_definition": "A candidate passes validation and the single held-out final test within the repair budget",
               "claims": "Descriptive paired sample only; no guaranteed benefit, significance or general causal claim.",
               "arms": {}, "paired": []}
    for arm in ["off", "on"]:
        rows = [row for row in results if row["history_mode"] == arm]
        values = {"observed_units": len(rows), "missing_units": planned_pairs - len(rows),
                  "denominator": planned_pairs,
                  "first_passes": sum(row["first_pass"] for row in rows),
                  "final_passes": sum(row["final_pass"] for row in rows),
                  "errors": sum(row["status"] == "error" for row in rows)}
        values.update(first_pass_rate=values["first_passes"] / planned_pairs,
                      final_pass_rate=values["final_passes"] / planned_pairs)
        for name in ["repairs", "calls", "observed_prompt_tokens", "observed_output_tokens",
                     "provider_attempt_errors", "transport_attempt_errors", "usage_missing_attempts", "wall_seconds"]:
            values[name] = sum(row[name] for row in rows)
        summary["arms"][arm] = values
    pairs, duplicate_units = {}, []
    index_key = "repeat" if protocol_kind == CLOUD_PROTOCOL else "seed"
    for row in results:
        pair = pairs.setdefault((row["profile"], row.get(index_key)), {})
        if row["history_mode"] in pair:
            duplicate_units.append(f"Duplicate unit: {row['profile']} {index_key}={row.get(index_key)} {row['history_mode']}")
        pair[row["history_mode"]] = row
    for (profile, seed), arms in sorted(pairs.items(), key=lambda item: str(item[0])):
        complete = {"off", "on"} <= set(arms)
        summary["paired"].append({"profile": profile, index_key: seed, "complete": complete,
                                  "first_pass_delta": int(arms["on"]["first_pass"]) - int(arms["off"]["first_pass"]) if complete else None,
                                  "final_pass_delta": int(arms["on"]["final_pass"]) - int(arms["off"]["final_pass"]) if complete else None})
    summary["first_pass_rate_delta"] = summary["arms"]["on"]["first_pass_rate"] - summary["arms"]["off"]["first_pass_rate"]
    summary["final_pass_rate_delta"] = summary["arms"]["on"]["final_pass_rate"] - summary["arms"]["off"]["final_pass_rate"]
    violations = duplicate_units + [item for row in results for item in row["prompt_audit_violations"]]
    summary["prompt_audit_violations"] = violations
    if provider == "deepseek" and protocol_kind != CLOUD_PROTOCOL:
        summary["comparison_limitation"] = (
            "This fixed-seed, installed-digest protocol does not support DeepSeek; "
            "cloud observations are real calls but not a validated paired-seed ablation.")
    complete = (len(results) == 2 * planned_pairs and len(pairs) == planned_pairs
                and all(row["complete"] for row in summary["paired"]))
    if provider == "deepseek" and protocol_kind == CLOUD_PROTOCOL:
        summary["protocol_kind"] = protocol_kind
        summary["comparison_limitations"] = CLOUD_LIMITATIONS
        summary["cloud_identity_observations"] = _cloud_identity_summary(results)
        violations.extend(summary["cloud_identity_observations"]["violations"])
        summary["valid_comparison_definition"] = "All planned paired trials and audits completed without protocol violations; not proof of fixed cloud weights or causal efficacy"
        summary["valid_comparison"] = complete and not violations
    else:
        summary["valid_comparison"] = provider == "ollama" and complete and not violations
    summary["protocol_complete"] = complete
    summary["paired_outcomes"] = {
        stage: {"history_wins": sum(row[stage + "_delta"] == 1 for row in summary["paired"]),
                "history_losses": sum(row[stage + "_delta"] == -1 for row in summary["paired"]),
                "ties": sum(row[stage + "_delta"] == 0 for row in summary["paired"]),
                "incomplete_pairs": planned_pairs - sum(row["complete"] for row in summary["paired"])}
        for stage in ("first_pass", "final_pass")}
    summary["status"] = "complete" if complete else "incomplete"
    summary["benefit_observed_in_sample"] = (summary["first_pass_rate_delta"] > 0 or summary["final_pass_rate_delta"] > 0) if summary["valid_comparison"] else None
    summary["sampling_by_unit"] = [{"profile": row["profile"], index_key: row.get(index_key),
                                    "history_mode": row["history_mode"],
                                    "observed_options": list({canonical_hash(options): options
                                        for options in row.get("actual_generation_options", [])}.values())}
                                   for row in results]
    return summary


def run_ablation(source, snapshot, output, profiles=None, seeds=None, provider="ollama",
                 model=None, base_url=None, runner="docker", max_repairs=2, repeats=None):
    if provider == "deepseek":
        if seeds is not None:
            raise ValueError("DeepSeek does not support fixed-seed/model-digest trials; use repeats, not seeds")
        return _run_cloud_ablation(source, snapshot, output, profiles, 2 if repeats is None else repeats,
                                   model, base_url, runner, max_repairs)
    if repeats is not None:
        raise ValueError("repeats is only for DeepSeek; use seeds for Ollama/mock")
    seeds = (11, 29) if seeds is None else seeds
    model, base_url = resolve_settings(provider, model, base_url or os.getenv("OLLAMA_URL") or "http://127.0.0.1:11435")
    if provider not in {"ollama", "mock"}:
        raise ValueError("Unsupported ablation provider: " + provider)
    source, snapshot, output = map(lambda value: Path(value).resolve(), (source, snapshot, output))
    profiles = DEFAULT_PROFILES if profiles is None else profiles
    if not profiles or not seeds or len(set(seeds)) != len(seeds):
        raise ValueError("Need nonempty profiles and unique seeds")
    names = [profile["id"] for profile in profiles]
    if len(set(names)) != len(names) or any(not re.fullmatch(r"[a-z][a-z0-9_]*", name) for name in names):
        raise ValueError("Profile IDs must be unique safe lowercase names")
    frozen = validate_snapshot(snapshot, profiles)
    package_hashes = _package_hashes()
    inputs = _input_hashes(source)
    model_identity = ollama_model_identity(base_url, model) if provider == "ollama" else None
    configs = {profile["id"]: _profile_config(source, profile, seeds[0], "off", max_repairs).model_dump()
               for profile in profiles}
    protocol = {"schema_version": 1, "profiles": profiles, "seeds": list(seeds), "provider": provider,
                "model": model, "model_identity": model_identity,
                "runner": runner, "base_url": base_url, "max_repairs": max_repairs,
                "snapshot_sha256": frozen["graph_sha256"], "package_hashes": package_hashes,
                "input_hashes": inputs, "configs": configs,
                "order": "Alternate off/on and on/off across pairs to reduce order effects",
                "history_treatment": "Only cross-run verified history is toggled; current-run error feedback stays enabled"}
    protocol["protocol_sha256"] = canonical_hash(protocol)
    output.mkdir(parents=True, exist_ok=True)
    protocol_path = output / "protocol.json"
    if protocol_path.exists() and json.loads(protocol_path.read_text()) != protocol:
        raise ValueError("Cannot resume: protocol, code, input data or frozen history changed")
    _write(protocol_path, protocol)
    results, index = [], 0

    def assert_integrity(check_model=False):
        try:
            if _package_hashes() != package_hashes or _input_hashes(source) != inputs:
                raise ValueError("Experiment code or input data changed during execution")
            current = validate_snapshot(snapshot, profiles)
            if current != frozen:
                raise ValueError("Frozen history manifest changed during execution")
            if check_model and provider == "ollama" and ollama_model_identity(base_url, model) != model_identity:
                raise ValueError("Installed model digest changed during execution")
        except Exception as exc:
            summary = aggregate_results(results, len(profiles) * len(seeds), provider)
            summary.update(valid_comparison=False, benefit_observed_in_sample=None,
                           integrity_error=f"{type(exc).__name__}: {exc}",
                           protocol_sha256=protocol["protocol_sha256"])
            _write(output / "raw-results.json", results)
            _write(output / "aggregate.json", summary)
            _write(output / "integrity-error.json", {"error": summary["integrity_error"],
                   "completed_units": len(results), "model_identity_at_start": model_identity})
            raise

    for profile in profiles:
        expected = [item["lesson_id"] for item in frozen["evidence"]
                    if item["task"] == profile["task"] and item["algorithm"] == profile["algorithm"]]
        for seed in seeds:
            order = ["off", "on"] if index % 2 == 0 else ["on", "off"]
            index += 1
            for history in order:
                assert_integrity()
                unit = output / "units" / f"{profile['id']}_seed{seed}_{history}"
                result_path = unit / "result.json"
                if result_path.exists():
                    result = json.loads(result_path.read_text())
                    if result.get("protocol_sha256") != protocol["protocol_sha256"]:
                        raise ValueError("Stored unit belongs to another protocol")
                    results.append(result)
                    continue
                if unit.exists():
                    raise ValueError("Interrupted unit has no result; retain it and use a fresh output directory: " + str(unit))
                _copy_inputs(source, unit, snapshot)
                config = _profile_config(source, profile, seed, history, max_repairs)
                print(f"Ablation {profile['id']} seed={seed} history={history}", flush=True)
                factory = Factory(unit, provider=provider, model=model, base_url=base_url,
                                  runner=runner, config=config)
                start, error = time.perf_counter(), None
                try:
                    factory.run(profile["description"])
                except Exception as exc:  # Preserve failed provider and workflow units in the denominator.
                    error = f"{type(exc).__name__}: {exc}"
                result = collect_unit(factory, profile, seed, history, time.perf_counter() - start,
                                      error, expected)
                result["protocol_sha256"] = protocol["protocol_sha256"]
                _write(result_path, result)
                results.append(result)
                _write(output / "raw-results.json", results)
                _write(output / "aggregate.json", aggregate_results(results, len(profiles) * len(seeds), provider))
    assert_integrity(check_model=True)
    _write(output / "raw-results.json", results)
    summary = aggregate_results(results, len(profiles) * len(seeds), provider)
    summary["protocol_sha256"] = protocol["protocol_sha256"]
    summary["integrity_verification"] = {"code_inputs_history": "passed",
                                         "model_identity_start_end": model_identity,
                                         "model_digest_unchanged": provider == "ollama"}
    _write(output / "aggregate.json", summary)
    return summary


